/*
 * setup-service-files.js — generate the headless-SERVER runtime files on
 * Windows. Run by ops-server-install-service.bat via the installed app's
 * Electron binary in ELECTRON_RUN_AS_NODE mode (no separate Node needed):
 *
 *   set ELECTRON_RUN_AS_NODE=1
 *   "C:\Program Files\Ops Control\Ops Control.exe" setup-service-files.js <opsHome> <appDir> <port>
 *
 * Writes (all under <opsHome> = C:\ProgramData\OpsControl):
 *   • server.env            — env + 64-hex secrets (only if absent; never
 *                             rotates existing keys → no surprise 2FA lockout)
 *   • run-server.bat        — wrapper: sources env, runs Electron-as-node
 *   • OpsControlServer.xml   — Task Scheduler definition (boot + SYSTEM +
 *                             hidden + restart-on-failure)
 *
 * Doing the file generation in Node (not .bat) avoids cmd quoting/`>>`/paren
 * escaping traps. No secret is ever printed — only the keys' destination file.
 */
'use strict';
/* global process, console, Buffer */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const opsHome = process.argv[2];
const appDir = process.argv[3];
const port = process.argv[4] || '3000';
if (!opsHome || !appDir) {
  console.error('usage: setup-service-files.js <opsHome> <appDir> [port]');
  process.exit(1);
}

const dataDir = path.join(opsHome, 'data');
const logDir = path.join(opsHome, 'logs');
const envFile = path.join(opsHome, 'server.env');
const wrapper = path.join(opsHome, 'run-server.bat');
const taskXml = path.join(opsHome, 'OpsControlServer.xml');
const electron = path.join(appDir, 'Ops Control.exe');
const serverEntry = path.join(appDir, 'resources', 'app', 'server', 'index.js');
const appWork = path.join(appDir, 'resources', 'app');

fs.mkdirSync(dataDir, { recursive: true });
fs.mkdirSync(logDir, { recursive: true });

if (!fs.existsSync(serverEntry)) {
  console.error('ERROR: server entry not found: ' + serverEntry);
  console.error('Cai ban "Ops Control SERVER Setup ….exe" truoc (mac dinh C:\\Program Files\\Ops Control).');
  process.exit(2);
}

// ── server.env (only when missing) ──────────────────────────────────────────
if (fs.existsSync(envFile)) {
  console.log('server.env da co — giu nguyen khoa (khong sinh lai).');
} else {
  const key = () => crypto.randomBytes(32).toString('hex');
  const env = [
    '# Ops Control headless SERVER env (admin-only). KHONG commit.',
    'NODE_ENV=production',
    'OPS_PORT=' + port,
    'PORT=' + port,
    'DATA_DIR=' + dataDir,
    'OPS_LICENSE_FILE=' + path.join(dataDir, 'license.json'),
    'OPS_ALLOW_SAME_ORIGIN=1',
    'OPS_DATA_BACKEND=sqlite',
    'OPS_BACKUP_SCHEDULE=1',
    'OPS_AUDIT_RETENTION=1',
    'OPS_TOTP_KEY=' + key(),
    'OPS_KIOSK_KEY=' + key(),
    'OPS_EXPORT_HMAC_KEY=' + key(),
    '# Bat tinh nang (mac dinh tat) neu can:',
    '# OPS_FEATURE_PLANNING=1',
    '# OPS_FEATURE_KIOSK=1',
    '# Gioi han CORS thay same-origin:',
    '# OPS_CORS_ORIGINS=http://10.102.3.61:' + port,
    '',
  ].join('\r\n');
  fs.writeFileSync(envFile, env);
  console.log('wrote ' + envFile + ' (secrets stay only in this file)');
}

// ── run-server.bat (wrapper sourced by the scheduled task) ──────────────────
const wrap = [
  '@echo off',
  'rem Auto-generated by setup-service-files.js. Nguon env (co khoa) roi chay',
  'rem Electron o che do node thuan -> server headless, khong cua so.',
  'setlocal enableextensions',
  'set "OPS_HOME=' + opsHome + '"',
  'if exist "%OPS_HOME%\\server.env" for /f "usebackq eol=# tokens=1,* delims==" %%A in ("%OPS_HOME%\\server.env") do set "%%A=%%B"',
  'set "ELECTRON_RUN_AS_NODE=1"',
  'cd /d "' + appWork + '"',
  '"' + electron + '" "' + serverEntry + '" >> "%OPS_HOME%\\logs\\server.out.log" 2>> "%OPS_HOME%\\logs\\server.err.log"',
  '',
].join('\r\n');
fs.writeFileSync(wrapper, wrap);
console.log('wrote ' + wrapper);

// ── Task Scheduler XML (boot trigger, SYSTEM, hidden, restart-on-failure) ───
// S-1-5-18 = LOCAL SYSTEM (runs pre-login). PT0S = no execution time limit.
const xml = [
  '<?xml version="1.0" encoding="UTF-16"?>',
  '<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">',
  '  <RegistrationInfo>',
  '    <Description>Ops Control headless SERVER (auto-start at boot, before login)</Description>',
  '  </RegistrationInfo>',
  '  <Triggers>',
  '    <BootTrigger><Enabled>true</Enabled></BootTrigger>',
  '  </Triggers>',
  '  <Principals>',
  '    <Principal id="Author">',
  '      <UserId>S-1-5-18</UserId>',
  '      <RunLevel>HighestAvailable</RunLevel>',
  '    </Principal>',
  '  </Principals>',
  '  <Settings>',
  '    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>',
  '    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>',
  '    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>',
  '    <AllowHardTerminate>true</AllowHardTerminate>',
  '    <StartWhenAvailable>true</StartWhenAvailable>',
  '    <RunOnlyIfNetworkAvailable>false</RunOnlyIfNetworkAvailable>',
  '    <IdleSettings><StopOnIdleEnd>false</StopOnIdleEnd><RestartOnIdle>false</RestartOnIdle></IdleSettings>',
  '    <AllowStartOnDemand>true</AllowStartOnDemand>',
  '    <Enabled>true</Enabled>',
  '    <Hidden>true</Hidden>',
  '    <ExecutionTimeLimit>PT0S</ExecutionTimeLimit>',
  '    <RestartOnFailure><Interval>PT1M</Interval><Count>999</Count></RestartOnFailure>',
  '  </Settings>',
  '  <Actions Context="Author">',
  '    <Exec>',
  '      <Command>' + wrapper + '</Command>',
  '    </Exec>',
  '  </Actions>',
  '</Task>',
  '',
].join('\r\n');
// schtasks prefers UTF-16LE with BOM for /XML import.
fs.writeFileSync(taskXml, Buffer.from('﻿' + xml, 'utf16le'));
console.log('wrote ' + taskXml);
console.log('OK');
