/**
 * build-bytecode.js — compile 4 file IP cốt lõi sang V8 bytecode (.jsc).
 *
 * Lý do (Sprint 4 — Bảo mật):
 *   Codebase Ops Control hiện chứa 4 module là IP cốt lõi của doanh
 *   nghiệp (công thức tính giá in, phân bổ ink, tối ưu layout, tính
 *   diện tích in). Khi đóng gói desktop, file JS source nằm trong
 *   app.asar và rất dễ extract:
 *
 *     npx @electron/asar extract app.asar dist/
 *
 *   → đối thủ thấy được toàn bộ thuật toán pricing.
 *
 *   bytenode compile các file này sang V8 bytecode `.jsc`:
 *     - Không decompile được dễ dàng (cần V8 internals + Electron
 *       version cụ thể)
 *     - Bytecode bind với version V8 của Electron đang dùng → user
 *       không thể swap sang Electron version khác để load
 *     - Vẫn chạy được khi require() bình thường
 *
 *   Đây KHÔNG phải bullet-proof DRM (no JS protection scheme is) —
 *   mục tiêu là raise cost-to-pirate để competitor thấy không
 *   worth-it.
 *
 * Workflow:
 *   1. Trước `electron-builder build`, chạy:
 *        node scripts/build-bytecode.js
 *      → ghi `.jsc` cạnh file `.js` gốc, file gốc được rename .js.bak.
 *   2. electron-builder package `.jsc` thay vì `.js` (do filter trong
 *      package.json > build.files).
 *   3. Tạo file shim `.js` (thin loader) gọi require .jsc — Node
 *      không tự nhận .jsc nên cần `bytenode.compileFile` API.
 *
 * IMPORTANT:
 *   - Chạy trên CÙNG Node version với Electron đang dùng (Node 20.x
 *     cho Electron 33). Bytecode KHÔNG cross-version.
 *   - Sau khi chạy, KHÔNG commit .jsc vào git (đã có gitignore).
 *
 * Chạy: node scripts/build-bytecode.js [--restore]
 *   --restore: revert lại từ .js.bak (cho dev iteration).
 */

'use strict';

const fs = require('node:fs');
const path = require('node:path');

// 4 file IP cốt lõi. Đường dẫn relative từ project root.
const IP_FILES = [
  'server/services/calcEngine.js',
  'server/services/inkCalcCore.js',
  'server/services/layoutOptimizer.js',
  'server/services/printAreaCore.js',
];

const PROJECT_ROOT = path.resolve(__dirname, '..');

// Shim template: thay vì source code, file `.js` chỉ load `.jsc` rồi
// re-export. Giữ tên cũ để các call site `require('./calcEngine')`
// không phải đổi.
function shimTemplate(jscRelative) {
  return `// AUTO-GENERATED by scripts/build-bytecode.js — DO NOT EDIT.
// Original source compiled to V8 bytecode for IP protection.
require('bytenode');
module.exports = require(${JSON.stringify(jscRelative)});
`;
}

function loadBytenode() {
  try {
    return require('bytenode');
  } catch (_) {
    console.error('bytenode not installed. Run:');
    console.error('  cd desktop && npm install --save-dev bytenode');
    process.exit(1);
  }
}

function buildOne(absJsPath) {
  const bytenode = loadBytenode();
  const dir = path.dirname(absJsPath);
  const base = path.basename(absJsPath, '.js');
  const jscPath = path.join(dir, `${base}.jsc`);
  const bakPath = `${absJsPath}.bak`;

  if (!fs.existsSync(absJsPath)) {
    console.warn(`[skip] ${path.relative(PROJECT_ROOT, absJsPath)} — file not found`);
    return false;
  }

  // Backup nếu chưa có
  if (!fs.existsSync(bakPath)) {
    fs.copyFileSync(absJsPath, bakPath);
  }

  // Compile from backup (source of truth) — tránh compile từ shim
  bytenode.compileFile({
    filename: bakPath,
    output: jscPath,
    compileAsModule: true,
  });

  // Replace source with shim
  fs.writeFileSync(absJsPath, shimTemplate(`./${base}.jsc`));

  const sz = fs.statSync(jscPath).size;
  console.log(`[build] ${path.relative(PROJECT_ROOT, absJsPath)} → .jsc (${sz} bytes)`);
  return true;
}

function restoreOne(absJsPath) {
  const dir = path.dirname(absJsPath);
  const base = path.basename(absJsPath, '.js');
  const jscPath = path.join(dir, `${base}.jsc`);
  const bakPath = `${absJsPath}.bak`;

  if (fs.existsSync(bakPath)) {
    fs.copyFileSync(bakPath, absJsPath);
    fs.unlinkSync(bakPath);
    console.log(`[restore] ${path.relative(PROJECT_ROOT, absJsPath)}`);
  }
  if (fs.existsSync(jscPath)) {
    fs.unlinkSync(jscPath);
  }
  return true;
}

function main() {
  const restore = process.argv.includes('--restore');
  console.log(restore ? '=== Restore mode ===' : '=== Bytecode compile ===');
  console.log('Project root:', PROJECT_ROOT);
  console.log('Node version:', process.version, '(must match Electron Node ABI)');
  console.log('');

  let count = 0;
  for (const rel of IP_FILES) {
    const abs = path.join(PROJECT_ROOT, rel);
    const ok = restore ? restoreOne(abs) : buildOne(abs);
    if (ok) count++;
  }
  console.log(`\n${restore ? 'Restored' : 'Compiled'} ${count}/${IP_FILES.length} files`);

  if (!restore) {
    console.log('\nNext steps:');
    console.log('  1. cd desktop && npm run build:mac (hoặc :win)');
    console.log('  2. Sau khi build xong, chạy: node scripts/build-bytecode.js --restore');
    console.log('     để revert source code cho dev iteration.');
  }
}

if (require.main === module) main();

module.exports = { IP_FILES, buildOne, restoreOne };
